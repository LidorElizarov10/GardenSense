# --- Part 2: RAG Engine ---

def retrieve_documents_rag(query):
    documents = list(GLOBAL_DOCS.values())
    doc_ids = list(GLOBAL_DOCS.keys())

    if not documents: return None, None

    vectorizer = TfidfVectorizer(stop_words='english')
    tfidf_matrix = vectorizer.fit_transform(documents)
    query_vec = vectorizer.transform([query])

    cosine_similarities = cosine_similarity(query_vec, tfidf_matrix).flatten()
    most_related_idx = cosine_similarities.argmax()

    if cosine_similarities[most_related_idx] > 0.1:
        doc_id = doc_ids[most_related_idx]
        return GLOBAL_DOCS[doc_id], DOC_METADATA[doc_id]

    return None, None

