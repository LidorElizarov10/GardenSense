def fetch_and_save_data_from_braude(feed_name: str, limit: int) -> str:
    """ Fetch from Braude Server -> Save to Firebase """
    limit = int(limit)
    print(f"🚀 Microservice 'Ingestion' started: Fetching {limit} items for feed '{feed_name}'...")

    try:
        response = requests.get(
            f"{BASE_URL}/history",
            params={"feed": feed_name, "limit": limit},
            timeout=60
        )
        response.raise_for_status()
        data = response.json()

        if "data" in data and len(data["data"]) > 0:
            messages = []
            samples = data["data"][::-1]

            for i, sample in enumerate(samples):
                raw_value = sample["value"]
                server_time = sample["created_at"]
                temp_val = hum_val = soil_val = 0.0

                # JSON Parsing Logic
                if feed_name == "json":
                    payload = {}
                    if isinstance(raw_value, str):
                        try:
                            payload = json.loads(raw_value)
                        except:
                            payload = {}
                    elif isinstance(raw_value, dict):
                        payload = raw_value

                    temp_val = float(payload.get("temperature", 0))
                    hum_val = float(payload.get("humidity", 0))
                    soil_val = float(payload.get("soil", 0))
                else:
                    try: val_float = float(raw_value)
                    except: val_float = 0.0
                    if feed_name == "temperature": temp_val = val_float
                    elif feed_name == "humidity": hum_val = val_float
                    elif feed_name == "soil": soil_val = val_float

                reading = {
                    "timestamp": datetime.now().isoformat(),
                    "original_server_time": server_time,
                    "temperature": temp_val,
                    "humidity": hum_val,
                    "soil": soil_val,
                    "source": f"braude_server_{feed_name}"
                }

                if FBconn:
                    FBconn.post("/sensor_data", reading)
                    messages.append(f"💾 [{i+1}] Saved to DB: {feed_name}={raw_value}")
                else:
                    messages.append(f"⚠️ [{i+1}] Not saved (DB Error)")

            return "<br>".join(messages) + "<br>✨ Process Complete!"
        else:
            return f"⚠️ Server returned empty or invalid data."
    except Exception as e:
        return f"❌ Error: {str(e)}"

