# --- Part 1: Inverted Index ---

def clean_text(text):
    text = re.sub(r'[^a-zA-Z\s]', '', str(text))
    return text.lower()

def remove_stop_words(word_list):
    stop_words = set(stopwords.words('english'))
    stop_words.update(['use', 'used', 'using', 'study', 'paper', 'result', 'method', 'analysis', 'based'])
    return [w for w in word_list if w not in stop_words]

def apply_stemming(word_list):
    stemmer = PorterStemmer()
    return [stemmer.stem(w) for w in word_list]

def build_inverted_index():
    global GLOBAL_INDEX, GLOBAL_DOCS, DOC_METADATA, FRONTEND_SEARCH_DATA

    print("🔄 Building Inverted Index...")
    GLOBAL_INDEX = defaultdict(list)
    GLOBAL_DOCS = {}
    FRONTEND_SEARCH_DATA = []

    for i, paper in enumerate(SAMPLE_PAPERS):
        doc_id = str(i)
        content = paper['content']
        title = paper['title']

        # Store for RAG
