class FirebaseClient:
    def __init__(self, url):
        self.url = url if url.endswith('/') else url + '/'

    def post(self, endpoint, data):
        endpoint = endpoint if not endpoint.startswith('/') else endpoint[1:]
        try:
            response = requests.post(f"{self.url}{endpoint}.json", json=data)
            return response.json()
        except Exception as e:
            print(f"❌ Firebase Post Error: {e}")
            return None

    def get(self, endpoint, param):
        endpoint = endpoint if not endpoint.startswith('/') else endpoint[1:]
        try:
            response = requests.get(f"{self.url}{endpoint}.json")
            return response.json()
        except Exception as e:
            print(f"❌ Firebase Get Error: {e}")
            return None

    def put(self, endpoint, child, data):
        endpoint = endpoint if not endpoint.startswith('/') else endpoint[1:]
        try:
            url = f"{self.url}{endpoint}{child}.json" if child else f"{self.url}{endpoint}.json"
            response = requests.put(url, json=data)
            return response.json()
        except Exception as e:
            print(f"❌ Firebase Put Error: {e}")
            return None

